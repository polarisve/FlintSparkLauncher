package org.jackhuang.hmcl.util;

import org.glavo.url.WebURL;
import org.jackhuang.hmcl.Metadata;
import org.jackhuang.hmcl.task.FileDownloadTask;
import org.jackhuang.hmcl.task.Task;
import org.jackhuang.hmcl.util.gson.JsonUtils;
import org.jackhuang.hmcl.util.platform.Platform;
import org.jetbrains.annotations.NotNullByDefault;
import org.jetbrains.annotations.Nullable;
import org.jetbrains.annotations.Unmodifiable;

import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.Reader;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Set;

import static java.nio.charset.StandardCharsets.UTF_8;
import static org.jackhuang.hmcl.util.gson.JsonUtils.listTypeOf;
import static org.jackhuang.hmcl.util.gson.JsonUtils.mapTypeOf;
import static org.jackhuang.hmcl.util.logging.Logger.LOG;

/// FSL: on-demand `javafx.web` support for the embedded Microsoft login window.
///
/// The launcher ships without `javafx.web` (about 35 MB). The first time the embedded login is used,
/// the matching `javafx.web`, `javafx.media` and (for JavaFX 24+) `jdk.jsobject` jars are downloaded
/// next to the other JavaFX jars, verified by SHA-1, and added to the running JVM on top of the
/// already loaded JavaFX modules. Later launches reuse the downloaded jars.
@NotNullByDefault
public final class FslWebComponent {

    /// Resource listing the web module jars per platform, generated by `generateOpenJFXWebDependencies`.
    private static final String DEPENDENCIES_LIST_FILE = "/assets/openjfx-web-dependencies.json";

    /// Directory that also holds the self-patched base JavaFX jars.
    private static final Path DEPENDENCIES_DIR = Metadata.DEPENDENCIES_DIRECTORY
            .resolve(Platform.CURRENT_PLATFORM.toString())
            .resolve("openjfx");

    /// Maven Central repository root.
    private static final String MAVEN_CENTRAL = "https://repo1.maven.org/maven2";

    /// Tencent Cloud Maven mirror root, preferred for users in mainland China.
    private static final String TENCENTCLOUD_MIRROR = "https://mirrors.cloud.tencent.com/nexus/repository/maven-public";

    /// Fully qualified name of the class used to detect whether `javafx.web` is usable.
    private static final String WEB_VIEW_CLASS = "javafx.scene.web.WebView";

    /// One jar to download, as listed in [#DEPENDENCIES_LIST_FILE].
    ///
    /// @param module     the module name the jar provides
    /// @param groupId    Maven group ID
    /// @param artifactId Maven artifact ID
    /// @param version    Maven version
    /// @param classifier Maven classifier (platform)
    /// @param sha1       expected SHA-1 of the jar
    private record Dependency(String module, String groupId, String artifactId, String version, String classifier,
                              String sha1) {

        /// Returns the jar file name.
        String fileName() {
            return artifactId + "-" + version + "-" + classifier + ".jar";
        }

        /// Returns where the jar is stored locally.
        Path localPath() {
            return DEPENDENCIES_DIR.resolve(fileName());
        }

        /// Returns the jar URL inside the given Maven repository.
        WebURL url(String repository) {
            return WebURL.parse(String.format("%s/%s/%s/%s/%s",
                    repository, groupId.replace('.', '/'), artifactId, version, fileName()));
        }
    }

    private FslWebComponent() {
    }

    /// Returns whether `javafx.web` can already be used in this JVM.
    public static boolean isLoaded() {
        try {
            Class.forName(WEB_VIEW_CLASS, false, FslWebComponent.class.getClassLoader());
            return true;
        } catch (ClassNotFoundException | LinkageError e) {
            return false;
        }
    }

    /// Returns whether `javafx.web` is loaded or can be downloaded and loaded on this platform.
    ///
    /// Downloading requires a known jar set whose version matches the running JavaFX, and JavaFX
    /// loaded as named modules.
    public static boolean isSupported() {
        if (isLoaded()) {
            return true;
        }
        return javafx.scene.Node.class.getModule().getLayer() != null && findDependencies() != null;
    }

    /// Finds the jars matching the current platform and the running JavaFX version.
    ///
    /// @return the jars, or `null` if this platform or JavaFX version has no known `javafx.web` build
    private static @Nullable @Unmodifiable List<Dependency> findDependencies() {
        String runtimeVersion = System.getProperty("javafx.runtime.version", "");

        Map<String, Map<String, List<Dependency>>> all;
        //noinspection DataFlowIssue
        try (InputStream input = FslWebComponent.class.getResourceAsStream(DEPENDENCIES_LIST_FILE);
             Reader reader = new InputStreamReader(input, UTF_8)) {
            all = JsonUtils.GSON.fromJson(reader, mapTypeOf(String.class, mapTypeOf(String.class, listTypeOf(Dependency.class))));
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }

        @Nullable Map<String, List<Dependency>> platform = all.get(Platform.CURRENT_PLATFORM.toString());
        if (platform == null) {
            return null;
        }

        for (List<Dependency> dependencies : platform.values()) {
            if (dependencies.isEmpty()) {
                continue;
            }
            String version = dependencies.get(0).version();
            // javafx.runtime.version looks like "25+29" or "21.0.8+5"
            if (runtimeVersion.equals(version)
                    || runtimeVersion.startsWith(version + "+")
                    || runtimeVersion.startsWith(version + "-")) {
                return List.copyOf(dependencies);
            }
        }

        LOG.warning("No javafx.web build matches JavaFX " + runtimeVersion + " on " + Platform.CURRENT_PLATFORM);
        return null;
    }

    /// Returns whether the local copy of the jar exists and matches its checksum.
    private static boolean isValid(Dependency dependency) {
        Path path = dependency.localPath();
        if (!Files.isRegularFile(path)) {
            return false;
        }
        try {
            return DigestUtils.digestToString("SHA-1", path).equalsIgnoreCase(dependency.sha1());
        } catch (IOException e) {
            LOG.warning("Failed to verify " + path, e);
            return false;
        }
    }

    /// Creates a task that downloads any missing jars and then loads `javafx.web`.
    ///
    /// The task does nothing if `javafx.web` is already loaded.
    ///
    /// @return the install task
    public static Task<Void> getInstallTask() {
        return Task.composeAsync(() -> {
            if (isLoaded()) {
                return null;
            }

            @Nullable List<Dependency> dependencies = findDependencies();
            if (dependencies == null) {
                throw new UnsupportedOperationException("javafx.web is not available for this platform");
            }

            Files.createDirectories(DEPENDENCIES_DIR);

            List<String> repositories = System.getProperty("user.country", "").equalsIgnoreCase("CN")
                    ? List.of(TENCENTCLOUD_MIRROR, MAVEN_CENTRAL)
                    : List.of(MAVEN_CENTRAL, TENCENTCLOUD_MIRROR);

            List<FileDownloadTask> downloads = new ArrayList<>();
            for (Dependency dependency : dependencies) {
                if (!isValid(dependency)) {
                    downloads.add(new FileDownloadTask(
                            repositories.stream().map(dependency::url).toList(),
                            dependency.localPath(),
                            new FileDownloadTask.IntegrityCheck("SHA-1", dependency.sha1())));
                }
            }

            return Task.allOf(downloads).thenRunAsync(() -> load(dependencies));
        });
    }

    /// Adds the downloaded jars to the running JVM.
    private static synchronized void load(List<Dependency> dependencies) throws ReflectiveOperationException {
        if (isLoaded()) {
            return;
        }
        LOG.info("Loading javafx.web from " + DEPENDENCIES_DIR);
        Path[] jars = dependencies.stream().map(Dependency::localPath).toArray(Path[]::new);
        JavaFXPatcher.patchExtraModules(Set.of("javafx.web"), jars);
        if (!isLoaded()) {
            throw new IllegalStateException("javafx.web is still unavailable after loading");
        }
    }
}
